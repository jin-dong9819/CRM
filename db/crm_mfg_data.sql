-- 4. 产品主表（低值易耗小件 SKU）
-- ------------------------------------------------------------
CREATE TABLE crm_product (
  id           BIGINT        NOT NULL AUTO_INCREMENT COMMENT '产品ID',
  product_code VARCHAR(32)   NOT NULL COMMENT '产品编码',
  product_name VARCHAR(100)  NOT NULL COMMENT '产品名称',
  category_id  BIGINT        NOT NULL COMMENT '分类ID',
  brand        VARCHAR(32)            DEFAULT NULL COMMENT '品牌',
  model        VARCHAR(64)            DEFAULT NULL COMMENT '型号 / 零件号',
  spec         VARCHAR(255)           DEFAULT NULL COMMENT '规格参数',
  fitment      VARCHAR(120)           DEFAULT NULL COMMENT '适用车型',
  unit         VARCHAR(16)   NOT NULL DEFAULT '件' COMMENT '计量单位',
  price        DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '标准售价（元）',
  cost_price   DECIMAL(12,2) NOT NULL DEFAULT 0 COMMENT '成本价（元）',
  status       TINYINT       NOT NULL DEFAULT 1 COMMENT '状态 1在售 0停售',
  remark       VARCHAR(255)           DEFAULT NULL COMMENT '备注',
  create_time  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP,
  update_time  DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_code (product_code),
  KEY idx_category (category_id),
  KEY idx_brand (brand),
  KEY idx_fitment (fitment)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='产品目录（汽车易损件与养护用品）';

